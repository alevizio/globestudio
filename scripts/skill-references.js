const describeDots = (settings) =>
  settings.renderMode === "solid"
    ? `solid land, fill ${code(settings.worldFill)}, outline ${code(settings.worldStroke)}`
    : `${settings.shape} dots, ${code(settings.dotColor)}, density ${settings.density}, size ${settings.dotSize}`;

const describeBackground = (settings) => {
  if (settings.transparent || settings.backgroundStyle === "transparent") return "transparent";
  if (settings.backgroundStyle === "solid") return `solid ${code(settings.background)}`;
  return settings.backgroundStyle;
};

const onOff = (value) => (value ? "on" : "off");

