// embed.js data-* attributes and the /embed parameter each one sets, then
// the ones it reads for the iframe itself.
const loaderAttributes = () => {
  const source = read("public/embed.js");
  const map = source.match(/var ATTRIBUTE_MAP = \{([\s\S]*?)\n\s*\};/)[1].replace(/\/\/.*$/gm, "");
  const params = [...map.matchAll(/"?([\w-]+)"?:\s*"(\w+)"/g)].map(([, attribute, param]) => [code(`data-${attribute}`), code(param), ""]);
  const own = [...source.matchAll(/(?:getAttribute\("data-(\w+)"\)|dataset\.(\w+))\s*\|\|\s*"([^"]*)"/g)].map(
    ([, attribute, key, fallback]) => [code(`data-${attribute ?? key}`), attribute === "height" ? "the host's height" : attribute === "title" ? "the iframe title" : code(key), code(fallback)],
  );
  return [...params, ...own];
};

// The query parameters /embed reads, as parseParams in embed-view.jsx reads
// them: each name with its reader and that reader's arguments (the fallback,
// then the range).
const readEmbedParams = () => {
  const source = read("src/components/embed-view.jsx");
  const body = source.match(/const parseParams = \(search, shareConfig\) => \{([\s\S]*?)\n\};/)[1];
  const seen = new Map();
  for (const [, kind, name, args] of body.matchAll(/\b(params\.get|sizeNum|num|bool)\("(\w+)"(?:,\s*((?:[^()]|\([^()]*\))*))?\)/g)) {
    if (!seen.has(name)) seen.set(name, { kind, args: args ? args.split(",").map((arg) => arg.trim()) : [] });
  }
  return { body, seen };
};

