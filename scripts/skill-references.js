const schema = JSON.parse(read("public/schema/config.json"));
const def = (prop) => (prop.$ref ? { ...schema.$defs[prop.$ref.replace("#/$defs/", "")], ...prop } : prop);
const HEX_PATTERN = schema.$defs.hex.pattern;

// What a property takes, in words, from its schema entry.
const accepts = (prop) => {
  const full = def(prop);
  const types = [full.type].flat().filter(Boolean);
  if (prop.$ref === "#/$defs/gradient") return "gradient or null (see Gradients)";
  if (full.anyOf) return "`all`, a postal code or a FIPS code (see US states)";
  if (full.enum) return list(full.enum.map(code));
  if (types.includes("array")) return `array of {lat, lng, value}, at most ${full.maxItems}`;
  if (types.includes("object")) return "object or null (see Custom shapes)";
  const parts = [];
  const range = () => `${number(full.minimum)} to ${number(full.maximum)}`;
  if (types.includes("number") && types.includes("boolean")) parts.push(`${range()}, or true or false`);
  else if (types.includes("number")) parts.push(range());
  else if (types.includes("boolean")) parts.push("true or false");
  else if (full.pattern === HEX_PATTERN) parts.push(types.includes("null") ? "hex color or null" : "hex color");
  else if (full.maxLength) parts.push(`text, up to ${number(full.maxLength)} characters`);
  else if (full.pattern && full.examples) parts.push(`text such as ${list(full.examples.map(code))}`);
  else if (types.includes("string")) parts.push("text");
  return parts.join("");
};

